# Nonce Reuse Attack Demonstration
# =============================================================================

def sign_with_known_nonce(message: str, private_key: int, k: int) -> Tuple[int, int]:
    """
    Sign with a specified nonce k. NEVER do this in production.
    Used here solely to demonstrate the nonce-reuse vulnerability.
    """
    z = hash_message(message)
    R = scalar_multiply(k, G)
    r = R.x % N
    k_inv = mod_inverse(k, N)
    s = (k_inv * (z + r * private_key)) % N
    return (r, s)


def nonce_reuse_attack(
    msg1: str, sig1: Tuple[int, int],
    msg2: str, sig2: Tuple[int, int]
) -> Optional[int]:
    """
    Extract the private key from two signatures that used the same nonce.

    Given:
      s₁ = k⁻¹(z₁ + r·d) mod n
      s₂ = k⁻¹(z₂ + r·d) mod n

    Subtract:
      s₁ - s₂ = k⁻¹(z₁ - z₂) mod n

    Solve for k:
      k = (z₁ - z₂) · (s₁ - s₂)⁻¹ mod n

    Then recover d:
      d = (s₁·k - z₁) · r⁻¹ mod n

    This is exactly how the PS3 master signing key was stolen in 2010.
    """
    r1, s1 = sig1
    r2, s2 = sig2

    # Both signatures must have the same r (same nonce → same R → same r)
    if r1 != r2:
        print("  Signatures don't share the same r — different nonces were used.")
        return None

    z1 = hash_message(msg1)
    z2 = hash_message(msg2)

    # Recover the nonce k
    # k = (z1 - z2) * (s1 - s2)⁻¹ mod n
    ds = (s1 - s2) % N
    dz = (z1 - z2) % N
    k_recovered = (dz * mod_inverse(ds, N)) % N

    # Recover the private key d
    # d = (s1 * k - z1) * r⁻¹ mod n
    r_inv = mod_inverse(r1, N)
    d_recovered = ((s1 * k_recovered - z1) * r_inv) % N

    return d_recovered


