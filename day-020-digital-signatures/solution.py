"""
Day 020: Digital Signatures (ECDSA) from Scratch

A complete implementation of the Elliptic Curve Digital Signature Algorithm
using the secp256k1 curve (same as Bitcoin/Ethereum). Built from first
principles — no cryptographic libraries for the core math.
"""

import hashlib
import secrets
from dataclasses import dataclass
from typing import Optional, Tuple


# =============================================================================
# secp256k1 Curve Parameters
# =============================================================================
# These are the exact parameters used by Bitcoin and Ethereum.
# The curve equation is y² = x³ + 7 (mod p).

# The prime defining the finite field F_p.
# All arithmetic is done modulo this number.
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F

# Curve coefficients: y² = x³ + ax + b
A = 0
B = 7

# Generator point G — a fixed point on the curve that generates the cyclic group.
# Every valid public key is some multiple of G.
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8

# Order of the generator point — the number of points in the subgroup generated by G.
# After n additions of G, you get back to the identity (point at infinity).
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


# =============================================================================
# Modular Arithmetic Helpers
# =============================================================================

def mod_inverse(a: int, m: int) -> int:
    """
    Compute the modular multiplicative inverse of a modulo m.

    Uses the extended Euclidean algorithm: finds x such that a*x ≡ 1 (mod m).
    This is essential because division doesn't exist in modular arithmetic —
    instead of dividing by a, we multiply by a's inverse.

    Time complexity: O(log m) — same as the Euclidean GCD algorithm.

    Could also use Fermat's little theorem (a^(m-2) mod m) since m is prime,
    but extended GCD is faster in practice and works for non-prime moduli too.
    """
    if a < 0:
        a = a % m

    # Extended Euclidean Algorithm
    # Maintains: old_r = old_s * a + old_t * m (we only need old_s)
    old_r, r = a, m
    old_s, s = 1, 0

    while r != 0:
        quotient = old_r // r
        old_r, r = r, old_r - quotient * r
        old_s, s = s, old_s - quotient * s

    if old_r != 1:
        raise ValueError(f"{a} has no inverse modulo {m}")

    return old_s % m


# =============================================================================
# Elliptic Curve Point Arithmetic
# =============================================================================

@dataclass
class Point:
    """
    A point on the secp256k1 elliptic curve.

    Points are either:
    - A concrete (x, y) coordinate pair on the curve
    - The "point at infinity" (identity element), represented by x=None, y=None

    The point at infinity acts like zero in addition: P + O = P.
    It's the result of adding a point to its own negation (P + (-P) = O).
    """
    x: Optional[int]
    y: Optional[int]

    @property
    def is_infinity(self) -> bool:
        return self.x is None and self.y is None

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, Point):
            return NotImplemented
        return self.x == other.x and self.y == other.y

    def __repr__(self) -> str:
        if self.is_infinity:
            return "Point(infinity)"
        # Show first/last 8 hex chars for readability
        x_hex = f"{self.x:064x}"
        y_hex = f"{self.y:064x}"
        return f"Point(x={x_hex[:8]}...{x_hex[-8:]}, y={y_hex[:8]}...{y_hex[-8:]})"


# The identity element — like zero for point addition
INFINITY = Point(None, None)

# The generator point
G = Point(GX, GY)


def point_add(p1: Point, p2: Point) -> Point:
    """
    Add two points on the secp256k1 curve.

    This is the fundamental group operation. Three cases:
    1. Either point is infinity → return the other (identity property)
    2. Points have same x but different y → they're inverses, return infinity
    3. Otherwise → compute the line through them, find third intersection, reflect

    For point doubling (p1 == p2), we use the tangent line instead.

    All arithmetic is mod P to stay in the finite field.
    """
    # Case 1: Identity element
    if p1.is_infinity:
        return p2
    if p2.is_infinity:
        return p1

    # Case 2: Points are inverses (same x, opposite y)
    # In F_p, "opposite y" means y1 + y2 ≡ 0 (mod P), i.e., y2 = P - y1
    if p1.x == p2.x and p1.y != p2.y:
        return INFINITY

    # Case 3a: Point doubling (tangent line)
    if p1.x == p2.x and p1.y == p2.y:
        # Slope of the tangent: dy/dx = (3x² + a) / (2y)
        # Division becomes multiplication by modular inverse
        slope = (3 * p1.x * p1.x + A) * mod_inverse(2 * p1.y, P) % P
    else:
        # Case 3b: Distinct points (secant line)
        # Slope = (y2 - y1) / (x2 - x1)
        slope = (p2.y - p1.y) * mod_inverse(p2.x - p1.x, P) % P

    # New point coordinates from the line-curve intersection
    # x3 = slope² - x1 - x2 (mod P)
    x3 = (slope * slope - p1.x - p2.x) % P
    # y3 = slope * (x1 - x3) - y1 (mod P)
    y3 = (slope * (p1.x - x3) - p1.y) % P

    return Point(x3, y3)


def scalar_multiply(k: int, point: Point) -> Point:
    """
    Compute k * point using the double-and-add algorithm.

    This is analogous to fast exponentiation (square-and-multiply):
    - Write k in binary: k = b_n b_{n-1} ... b_1 b_0
    - Scan bits from most significant to least
    - For each bit: double the accumulator
    - If the bit is 1: also add the base point

    Example: 13 * G = (1101)₂ * G
      Start with O (infinity)
      Bit 1: double(O) = O, add G → G
      Bit 1: double(G) = 2G, add G → 3G
      Bit 0: double(3G) = 6G
      Bit 1: double(6G) = 12G, add G → 13G

    Time complexity: O(log k) point operations — crucial because k is ~256 bits.
    Doing k sequential additions would take ~2²⁵⁶ operations (heat death of universe).

    WARNING: This implementation is NOT constant-time and leaks information about k
    through timing side channels. Production code must use constant-time algorithms
    (e.g., Montgomery ladder) to prevent private key extraction via timing attacks.
    """
    # Reduce k modulo the curve order — k*G = (k mod n)*G since G has order n
    k = k % N

    if k == 0:
        return INFINITY

    result = INFINITY
    addend = point

    while k:
        if k & 1:  # Current bit is 1
            result = point_add(result, addend)
        addend = point_add(addend, addend)  # Double
        k >>= 1  # Shift to next bit

    return result


# =============================================================================
# ECDSA: Key Generation, Signing, Verification
# =============================================================================

def hash_message(message: str) -> int:
    """
    Hash a message to an integer for signing.

    Uses SHA-256 (same as Bitcoin). The hash is interpreted as a big-endian
    integer and truncated to the bit-length of the curve order n.
    For secp256k1, n is 256 bits and SHA-256 produces 256 bits, so no
    truncation is needed — but we include the logic for correctness.
    """
    digest = hashlib.sha256(message.encode('utf-8')).digest()
    z = int.from_bytes(digest, 'big')

    # Truncate to the bit-length of n (for secp256k1 this is a no-op)
    bit_length = N.bit_length()
    z_bit_length = z.bit_length()
    if z_bit_length > bit_length:
        z >>= (z_bit_length - bit_length)

    return z


def generate_keypair() -> Tuple[int, Point]:
    """
    Generate an ECDSA key pair.

    Private key: a random integer d in [1, n-1]
    Public key: the point Q = d * G

    The security rests on the discrete logarithm problem:
    given Q and G, finding d is computationally infeasible.

    Returns:
        (private_key, public_key) tuple
    """
    # Generate a cryptographically secure random private key
    # secrets module uses the OS CSPRNG — suitable for key material
    private_key = secrets.randbelow(N - 1) + 1  # Range: [1, N-1]

    # Public key = private_key * G (scalar multiplication)
    public_key = scalar_multiply(private_key, G)

    return private_key, public_key


def sign(message: str, private_key: int) -> Tuple[int, int]:
    """
    Sign a message using ECDSA.

    Steps:
    1. Hash the message to get z
    2. Pick a random nonce k (MUST be unique per signature)
    3. Compute R = k*G, set r = R.x mod n
    4. Compute s = k⁻¹ * (z + r*d) mod n
    5. Return (r, s)

    The nonce k is the most security-critical value. If an attacker learns k
    for even one signature, they can compute the private key directly.
    If k is reused across two signatures, the private key leaks algebraically.

    In production, use RFC 6979 deterministic nonces instead of random ones.
    """
    z = hash_message(message)

    while True:
        # Step 2: Generate a random nonce k
        k = secrets.randbelow(N - 1) + 1

        # Step 3: Compute the curve point R = k * G
        R = scalar_multiply(k, G)
        r = R.x % N

        if r == 0:
            # Extremely unlikely but must handle — try another k
            continue

        # Step 4: Compute s = k⁻¹ * (z + r * private_key) mod N
        # This binds the message hash (z), the random point (r), and
        # the private key (d) together in a way that only k⁻¹ can untangle
        k_inv = mod_inverse(k, N)
        s = (k_inv * (z + r * private_key)) % N

        if s == 0:
            # Also extremely unlikely
            continue

        return (r, s)


def verify(message: str, signature: Tuple[int, int], public_key: Point) -> bool:
    """
    Verify an ECDSA signature.

    Steps:
    1. Check r, s are in [1, n-1]
    2. Hash the message to get z
    3. Compute w = s⁻¹ mod n
    4. Compute u₁ = z*w mod n, u₂ = r*w mod n
    5. Compute R' = u₁*G + u₂*Q
    6. Valid iff R'.x mod n == r

    Why this works (the beautiful algebra):
      u₁*G + u₂*Q
      = (z*s⁻¹)*G + (r*s⁻¹)*(d*G)
      = s⁻¹*(z + r*d)*G
      = (k⁻¹*(z + r*d))⁻¹ * (z + r*d) * G    [since s = k⁻¹*(z + r*d)]
      = k * G
      = R

    So R'.x should equal r = R.x mod n. QED.
    """
    r, s = signature

    # Step 1: Range check
    if not (1 <= r < N and 1 <= s < N):
        return False

    # Step 2: Hash the message
    z = hash_message(message)

    # Step 3: Compute w = s⁻¹ mod n
    w = mod_inverse(s, N)

    # Step 4: Compute u1, u2
    u1 = (z * w) % N
    u2 = (r * w) % N

    # Step 5: Compute R' = u1*G + u2*Q
    # This is the most expensive step — two scalar multiplications and one addition
    point1 = scalar_multiply(u1, G)
    point2 = scalar_multiply(u2, public_key)
    R_prime = point_add(point1, point2)

    if R_prime.is_infinity:
        return False

    # Step 6: Check r == R'.x mod n
    return R_prime.x % N == r


