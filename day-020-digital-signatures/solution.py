if __name__ == "__main__":
    print("=" * 70)
    print("ECDSA Digital Signatures — From Scratch")
    print("=" * 70)

    # --- Verify the generator point is on the curve ---
    print("\n[1] Verifying generator point G is on secp256k1...")
    lhs = pow(GY, 2, P)
    rhs = (pow(GX, 3, P) + B) % P
    assert lhs == rhs, "Generator point is NOT on the curve!"
    print(f"  y² mod p = {hex(lhs)[:20]}...")
    print(f"  x³+7 mod p = {hex(rhs)[:20]}...")
    print("  Match! G is on the curve.")

    # --- Key generation ---
    print("\n[2] Generating key pair...")
    private_key, public_key = generate_keypair()
    print(f"  Private key (d): {hex(private_key)[:20]}...{hex(private_key)[-8:]}")
    print(f"  Public key (Q):  {public_key}")

    # Verify public key is on the curve
    lhs = pow(public_key.y, 2, P)
    rhs = (pow(public_key.x, 3, P) + B) % P
    assert lhs == rhs, "Public key is NOT on the curve!"
    print("  Public key verified on curve.")

    # --- Signing ---
    message = "Send 1 BTC to Alice"
    print(f"\n[3] Signing message: '{message}'")
    signature = sign(message, private_key)
    r, s = signature
    print(f"  r = {hex(r)[:20]}...{hex(r)[-8:]}")
    print(f"  s = {hex(s)[:20]}...{hex(s)[-8:]}")

    # --- Verification ---
    print("\n[4] Verifying signature...")
    is_valid = verify(message, signature, public_key)
    print(f"  Valid: {is_valid}")
    assert is_valid, "Signature should be valid!"

    # --- Tampered message ---
    tampered = "Send 100 BTC to Alice"
    print(f"\n[5] Verifying with tampered message: '{tampered}'")
    is_valid_tampered = verify(tampered, signature, public_key)
    print(f"  Valid: {is_valid_tampered}")
    assert not is_valid_tampered, "Tampered message should NOT verify!"

    # --- Wrong key ---
    print("\n[6] Verifying with wrong public key...")
    _, wrong_key = generate_keypair()
    is_valid_wrong_key = verify(message, signature, wrong_key)
    print(f"  Valid: {is_valid_wrong_key}")
    assert not is_valid_wrong_key, "Wrong key should NOT verify!"

    # --- Nonce reuse attack ---
    print("\n[7] Demonstrating nonce reuse attack...")
    print("  (This is why nonce security is critical!)")

    # Sign two different messages with the SAME nonce — catastrophic!
    reuse_nonce = secrets.randbelow(N - 1) + 1
    msg_a = "Transfer 0.5 ETH to Bob"
    msg_b = "Transfer 0.5 ETH to Charlie"

    sig_a = sign_with_known_nonce(msg_a, private_key, reuse_nonce)
    sig_b = sign_with_known_nonce(msg_b, private_key, reuse_nonce)

    print(f"\n  Message A: '{msg_a}'")
    print(f"  Signature A: r={hex(sig_a[0])[:16]}..., s={hex(sig_a[1])[:16]}...")
    print(f"\n  Message B: '{msg_b}'")
    print(f"  Signature B: r={hex(sig_b[0])[:16]}..., s={hex(sig_b[1])[:16]}...")

    print(f"\n  Notice both signatures have the same r! (same nonce → same R point)")
    assert sig_a[0] == sig_b[0], "r values should match with same nonce"

    # An attacker who sees both signatures can extract the private key
    recovered_key = nonce_reuse_attack(msg_a, sig_a, msg_b, sig_b)

    if recovered_key is not None:
        print(f"\n  ATTACK SUCCESSFUL!")
        print(f"  Recovered private key: {hex(recovered_key)[:20]}...{hex(recovered_key)[-8:]}")
        print(f"  Original private key:  {hex(private_key)[:20]}...{hex(private_key)[-8:]}")
        assert recovered_key == private_key, "Recovered key should match!"
        print(f"  Keys match! The attacker now controls the wallet.")

    # --- Multiple signatures ---
    print("\n[8] Signing and verifying multiple messages...")
    messages = [
        "Hello, blockchain!",
        "The quick brown fox jumps over the lazy dog",
        "",  # Empty message — still works
        "🚀 To the moon!",  # Unicode
    ]

    for msg in messages:
        sig = sign(msg, private_key)
        valid = verify(msg, sig, public_key)
        display = msg if msg else "(empty string)"
        print(f"  '{display}' → valid={valid}")
        assert valid, f"Signature for '{display}' should be valid!"

    print("\n" + "=" * 70)
    print("All checks passed! ECDSA implementation is correct.")
    print("=" * 70)
